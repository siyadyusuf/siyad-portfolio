/** SAMPLE DATA: a sparse, deterministic calendar so the heatmap has something to show in mock mode. */
function sampleContributions(now: number): GithubResponse['contributions'] {
  const days: { date: string; count: number }[] = []
  let seed = 7
  const rand = () => ((seed = (seed * 16807) % 2147483647) / 2147483647)
  for (let i = 364; i >= 0; i--) {
    const d = new Date(now - i * day)
    const date = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
    const recent = i < 60 ? 0.22 : 0.06
    const r = rand()
    days.push({ date, count: r < recent ? 1 + Math.floor(rand() * (i < 30 ? 7 : 3)) : 0 })
  }
  return { total: days.reduce((s, d) => s + d.count, 0), days }
}

const delay = (ms: number) => new Promise((r) => setTimeout(r, ms))

export async function mockFetch(input: string, init: RequestInit): Promise<Response> {
  await delay(180 + Math.random() * 200)
  const url = new URL(input, window.location.origin)
  const path = url.pathname.replace(/^\/api/, '')
  const method = (init.method ?? 'GET').toUpperCase()
  let body: Record<string, unknown> = {}
  if (typeof init.body === 'string') {
    try {
      body = JSON.parse(init.body) as Record<string, unknown>
    } catch {
      return err(400, 'validation_error', 'body: Invalid JSON')
    }
  }
  const now = Date.now()

  // ---- Public posts
  if (method === 'GET' && path === '/posts') {
    const page = Math.max(1, parseInt(url.searchParams.get('page') ?? '1', 10) || 1)
    const limit = Math.min(50, Math.max(1, parseInt(url.searchParams.get('limit') ?? '10', 10) || 10))
    const pub = loadPosts().filter((p) => isPublic(p, now)).sort(byDateDesc)
    const slice = pub.slice((page - 1) * limit, page * limit)
    return json(200, {
      posts: slice.map((p) => ({ id: p.id, slug: p.slug, title: p.title, excerpt: excerptOf(p.content), publishedAt: p.publishedAt, sourceUrl: p.sourceUrl ?? null })),
      page,
      totalPages: Math.max(1, Math.ceil(pub.length / limit)),
    })
  }
  const postMatch = path.match(/^\/posts\/([^/]+)$/)
  if (method === 'GET' && postMatch) {
    const slug = decodeURIComponent(postMatch[1])
    const p = loadPosts().find((x) => x.slug === slug && isPublic(x, now))
    if (!p) return err(404, 'not_found', 'Post not found')
    return json(200, { id: p.id, slug: p.slug, title: p.title, content: p.content, publishedAt: p.publishedAt, updatedAt: p.updatedAt, sourceUrl: p.sourceUrl ?? null })
  }

  // ---- Auth
  if (method === 'POST' && path === '/auth/login') {
    if (body.password !== MOCK_ADMIN_PASSWORD) return err(401, 'invalid_password', 'Wrong password')
    sessionStorage.setItem(AUTH_KEY, '1')
    return json(200, { ok: true })
  }
  if (method === 'POST' && path === '/auth/logout') {
    sessionStorage.removeItem(AUTH_KEY)
    return json(200, { ok: true })
  }
  if (method === 'GET' && path === '/auth/me') return json(200, { authenticated: isAuthed() })

  // ---- Admin posts
  if (path.startsWith('/admin/posts')) {
    if (!isAuthed()) return err(401, 'unauthorized', 'Please log in')
    const posts = loadPosts()
    const idMatch = path.match(/^\/admin\/posts\/(\d+)$/)
    if (method === 'GET' && path === '/admin/posts') return json(200, { posts: [...posts].sort(byDateDesc) })
    if (method === 'POST' && path === '/admin/posts') {
      const input = body as Partial<AdminPostInput>
      const v = validatePostInput(input)
      if (v) return err(400, 'validation_error', v)
      let slug = input.slug
      if (slug) {
        if (posts.some((p) => p.slug === slug)) return err(409, 'slug_taken', 'That slug is already used')
      } else {
        const base = slugify(input.title!)
        slug = base
        for (let i = 2; posts.some((p) => p.slug === slug); i++) slug = `${base}-${i}`
      }
      const created: AdminPost = {
        id: posts.reduce((m, p) => Math.max(m, p.id), 0) + 1,
        slug,
        title: input.title!.trim(),
        content: input.content!,
        status: input.status!,
        publishedAt: new Date(input.publishedAt!).toISOString(),
        updatedAt: iso(now),
        sourceUrl: input.sourceUrl || null,
      }
      savePosts([...posts, created])
      return json(201, created)
    }
    if (idMatch) {
      const id = Number(idMatch[1])
      const existing = posts.find((p) => p.id === id)
      if (!existing) return err(404, 'not_found', 'Post not found')
      if (method === 'GET') return json(200, existing)
      if (method === 'PUT') {
        const input = body as Partial<AdminPostInput>
        const v = validatePostInput(input)
        if (v) return err(400, 'validation_error', v)
        const slug = input.slug ?? existing.slug
        if (posts.some((p) => p.slug === slug && p.id !== id)) return err(409, 'slug_taken', 'That slug is already used')
        const updated: AdminPost = {
          ...existing,
          slug,
          title: input.title!.trim(),
          content: input.content!,
          status: input.status!,
          publishedAt: new Date(input.publishedAt!).toISOString(),
          updatedAt: iso(now),
          sourceUrl: input.sourceUrl === undefined ? (existing.sourceUrl ?? null) : input.sourceUrl || null,
        }
        savePosts(posts.map((p) => (p.id === id ? updated : p)))
        return json(200, updated)
      }
      if (method === 'DELETE') {
        savePosts(posts.filter((p) => p.id !== id))
        return json(200, { ok: true })
      }
    }
  }

  // ---- Contact (5 per hour, like the backend)
  if (method === 'POST' && path === '/contact') {
    const input = body as Partial<ContactInput>
    const hourAgo = now - 3600_000
    while (contactLog.length && contactLog[0] < hourAgo) contactLog.shift()
    if (contactLog.length >= 5) return err(429, 'rate_limited', "You've sent a few messages already, try again later")
    contactLog.push(now)
    if (!input.name?.trim()) return err(400, 'validation_error', 'name: Required')
    if (!input.email || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(input.email)) return err(400, 'validation_error', 'email: Invalid email address')
    if (!input.message?.trim()) return err(400, 'validation_error', 'message: Required')
    // Honeypot filled: pretend success, send nothing (same as backend).
    return json(200, { ok: true })
  }

  // ---- GitHub
  if (method === 'GET' && path === '/github') {
    // Preview empty states in mock mode: add ?mockGithub=empty (no data) or ?mockGithub=null (contributions: null) to the page URL.
    const mode = new URLSearchParams(window.location.search).get('mockGithub')
    if (mode === 'empty') return json(200, { repos: [], recentActivity: [], contributions: { total: 0, days: [] } })
    if (mode === 'null') return json(200, { ...sampleGithub(), contributions: null })
    return json(200, sampleGithub())
  }

  return err(404, 'not_found', 'No such endpoint')
}


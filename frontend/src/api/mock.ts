function loadPosts(): AdminPost[] {
  try {
    const raw = localStorage.getItem(STORE_KEY)
    if (raw) return JSON.parse(raw) as AdminPost[]
  } catch {
    /* ignore */
  }
  const seeded = seedPosts()
  savePosts(seeded)
  return seeded
}

function savePosts(posts: AdminPost[]): void {
  try {
    localStorage.setItem(STORE_KEY, JSON.stringify(posts))
  } catch {
    /* ignore */
  }
}

const isAuthed = () => sessionStorage.getItem(AUTH_KEY) === '1'

// Same helpers as the backend's posts-repo.ts
function excerptOf(markdown: string, max = 180): string {
  const plain = markdown
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/[#>*_`~-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
  return plain.length <= max ? plain : plain.slice(0, max).replace(/\s+\S*$/, '') + '…'
}

const isPublic = (p: AdminPost, now: number) => p.status === 'published' && Date.parse(p.publishedAt) <= now
const byDateDesc = (a: AdminPost, b: AdminPost) => Date.parse(b.publishedAt) - Date.parse(a.publishedAt) || b.id - a.id

function json(status: number, body: unknown): Response {
  return new Response(JSON.stringify(body), { status, headers: { 'Content-Type': 'application/json' } })
}
const err = (status: number, code: string, message: string) => json(status, { error: { code, message } })

function validatePostInput(b: Partial<AdminPostInput>): string | null {
  if (!b.title || !b.title.trim()) return 'title: Required'
  if (!b.content || !b.content.trim()) return 'content: Required'
  if (!b.publishedAt || Number.isNaN(Date.parse(b.publishedAt))) return 'publishedAt: Invalid datetime'
  if (b.status !== 'draft' && b.status !== 'published') return 'status: Invalid option'
  if (b.sourceUrl && !isHttpUrl(b.sourceUrl)) return 'sourceUrl: must be an http(s) URL'
  if (b.slug !== undefined && !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(b.slug)) return 'slug: use lowercase letters, numbers and dashes'
  return null
}

